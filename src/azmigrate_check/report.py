def to_html(a: Assessment, title: str = "Azure Migration Readiness Report") -> str:
    e = html.escape
    s = _summary(a)
    cards = [
        ("Servers", s["servers"], ""),
        ("Ready", s["ready"], "ready"),
        ("Needs review", s["review"], "review"),
        ("Blocked", s["blocked"], "blocked"),
        ("Blockers", s["blockers"], "blocker"),
        ("Warnings", s["warnings"], "warning"),
    ]
    card_html = "".join(
        f'<div class="card"><b class="{cls}">{val}</b><span>{e(label)}</span></div>'
        for label, val, cls in cards
    )
    server_rows = []
    for srv in a.servers:
        status = a.server_status(srv.name)
        server_rows.append(
            "<tr>"
            f"<td>{e(srv.name)}</td>"
            f"<td>{e(f'{srv.os} {srv.os_version}'.strip() or '-')}</td>"
            f'<td class="num">{srv.cpu if srv.cpu is not None else "-"}</td>'
            f'<td class="num">{f"{srv.ram_gb:g}" if srv.ram_gb is not None else "-"}</td>'
            f'<td><span class="pill {status}">{_STATUS_LABEL[status]}</span></td>'
            f'<td class="num">{len(a.findings_for(srv.name))}</td>'
            "</tr>"
        )
    if a.findings:
        finding_rows = "".join(
            "<tr>"
            f'<td><span class="pill {f.severity.value}">{f.severity.value.upper()}</span></td>'
            f"<td>{e(f.rule_id)}</td><td>{e(f.server)}</td>"
            f"<td>{e(f.message)}</td><td>{e(f.remediation)}</td>"
            "</tr>"
            for f in a.findings
        )
        findings_html = (
            '<div class="table-wrap"><table><thead><tr><th>Severity</th><th>Rule</th>'
            "<th>Server</th><th>Finding</th><th>Remediation</th></tr></thead>"
            f"<tbody>{finding_rows}</tbody></table></div>"
        )
    else:
        findings_html = "<p>No findings. All servers passed the configured checks.</p>"

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{e(title)}</title>
<style>{_CSS}</style>
</head>
<body>
<main>
<h1>{e(title)}</h1>
<p class="meta">Assessment date: {e(a.as_of)} · Generated by azmigrate-check {e(__version__)}</p>
<div class="cards">{card_html}</div>
<h2>Servers</h2>
<div class="table-wrap"><table><thead><tr><th>Server</th><th>OS</th><th class="num">vCPU</th>
<th class="num">RAM (GB)</th><th>Status</th><th class="num">Findings</th></tr></thead>
<tbody>{"".join(server_rows)}</tbody></table></div>
<h2>Findings</h2>
{findings_html}
<p class="note">OS end-of-support dates come from a built-in catalog and may be overridden in
config. Verify them against vendor lifecycle pages before making decisions.</p>
</main>
</body>
</html>
"""
