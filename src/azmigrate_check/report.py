"""Render an Assessment as Markdown or self-contained HTML."""

from __future__ import annotations

import html

from azmigrate_check import __version__
from azmigrate_check.models import Assessment, Severity

_STATUS_LABEL = {"blocked": "Blocked", "review": "Needs review", "ready": "Ready"}


def _md_escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _summary(a: Assessment) -> dict[str, int]:
    statuses = [a.server_status(s.name) for s in a.servers]
    return {
        "servers": len(a.servers),
        "ready": statuses.count("ready"),
        "review": statuses.count("review"),
        "blocked": statuses.count("blocked"),
        "blockers": a.count(Severity.BLOCKER),
        "warnings": a.count(Severity.WARNING),
        "info": a.count(Severity.INFO),
    }


def to_markdown(a: Assessment, title: str = "Azure Migration Readiness Report") -> str:
    s = _summary(a)
    lines = [
        f"# {title}",
        "",
        f"Assessment date: {a.as_of} · Generated by azmigrate-check {__version__}",
        "",
        "## Summary",
        "",
        "| Servers | Ready | Needs review | Blocked | Blockers | Warnings | Info |",
        "|---:|---:|---:|---:|---:|---:|---:|",
        f"| {s['servers']} | {s['ready']} | {s['review']} | {s['blocked']} "
        f"| {s['blockers']} | {s['warnings']} | {s['info']} |",
        "",
        "## Servers",
        "",
        "| Server | OS | vCPU | RAM (GB) | Status | Findings |",
        "|---|---|---:|---:|---|---:|",
    ]
    for srv in a.servers:
        os_text = _md_escape(f"{srv.os} {srv.os_version}".strip() or "-")
        lines.append(
            f"| {_md_escape(srv.name)} | {os_text} | {srv.cpu if srv.cpu is not None else '-'} "
            f"| {f'{srv.ram_gb:g}' if srv.ram_gb is not None else '-'} "
            f"| {_STATUS_LABEL[a.server_status(srv.name)]} | {len(a.findings_for(srv.name))} |"
        )
    lines += ["", "## Findings", ""]
    if not a.findings:
        lines.append("No findings. All servers passed the configured checks.")
    else:
        lines += [
            "| Severity | Rule | Server | Finding | Remediation |",
            "|---|---|---|---|---|",
        ]
        for f in a.findings:
            lines.append(
                f"| {f.severity.value.upper()} | {f.rule_id} | {_md_escape(f.server)} "
                f"| {_md_escape(f.message)} | {_md_escape(f.remediation)} |"
            )
    lines += [
        "",
        "> OS end-of-support dates come from a built-in catalog and may be overridden in "
        "config. Verify them against vendor lifecycle pages before making decisions.",
        "",
    ]
    return "\n".join(lines)


